export function resolveUiLocale(locale?: string): string {
    const normalized = (locale ?? "en").replaceAll("_", "-").toLowerCase();
    if (normalized.startsWith("zh")) {
        return /(?:hant|tw|hk|mo)(?:-|$)/.test(normalized) ? "zh-TW" : "zh-CN";
    }
    if (normalized.startsWith("pt")) return "pt-BR";
    const base = normalized.split("-")[0];
    return Object.hasOwn(uiPacks, base) ? base : "en";
}

export function uiText(locale: string | undefined, key: UiKey): string {
    return uiPacks[resolveUiLocale(locale)]?.[uiKeys.indexOf(key)] || english[key];
}

export function languageDisplayName(code: string, locale: string, fallback: string): string {
    try { return new Intl.DisplayNames([locale], { type: "language" }).of(code) || fallback; }
    catch { return fallback; }
}
